# Данные отделений клиники. Врачи берутся из seed.py (те же ФИО и специальности,
# что загружены в базы clinic_a / clinic_b), распределены по отделениям.
from __future__ import annotations

from typing import Dict, List

# Импортируем списки врачей из seed.py — на сайте показываем тех же врачей,
# что есть в базе данных.
from seed import DOCTOR_NAMES, SPECIALTIES


def doctor_info(i: int) -> Dict[str, str]:
    """Сводка по врачу с порядковым номером i (1..30) — как в seed.make_doctor."""
    name = DOCTOR_NAMES[i - 1]
    specialty = SPECIALTIES[(i - 1) % len(SPECIALTIES)]
    cabinet = f"{100 + i}"
    # Стаж детерминированно выводим из номера врача (5–30 лет)
    exp = 5 + (i * 7) % 26
    if exp >= 20:
        category = "Высшая категория"
    elif exp >= 12:
        category = "Первая категория"
    else:
        category = "Вторая категория"
    degree = "Кандидат медицинских наук" if i % 7 == 0 else ""
    return {
        "name": name,
        "specialty": specialty,
        "cabinet": cabinet,
        "phone": f"+7 (900) 555-{i:02d}",
        "experience": f"{exp} лет",
        "category": category,
        "degree": degree,
    }


def department_doctors(specialties: List[str]) -> List[Dict[str, str]]:
    result = []
    for i in range(1, len(DOCTOR_NAMES) + 1):
        spec = SPECIALTIES[(i - 1) % len(SPECIALTIES)]
        if spec in specialties:
            result.append(doctor_info(i))
    return result


